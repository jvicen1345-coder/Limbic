/** Fisher-Yates, non-mutating. Not for anything security-sensitive — just varying display
 *  order (Clips lap order, Health & Wellness pool ordering). */
export function shuffle<T>(items: T[]): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
