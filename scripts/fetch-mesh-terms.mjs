#!/usr/bin/env node
// Regenerates src/lib/mesh-terms.ts from NLM's MeSH (Medical Subject Headings) tree
// file (https://nlmpubs.nlm.nih.gov/projects/mesh/<year>/meshtrees/mtrees<year>.bin).
// That file lists every MeSH descriptor together with its tree number(s) — e.g.
// " Knee;A01.378.610.450" — which is what lets this script pick out just the branches
// relevant to PT/rehab (anatomy, musculoskeletal/neuro conditions, physical therapy
// modalities, sports medicine, etc.) out of the ~30k descriptors in the full vocabulary,
// and bake the result into a small TypeScript file the app imports directly.
//
// Not fetched live at request time: same rationale as fetch-retraction-watch.mjs — MeSH
// is a large, slow-changing reference vocabulary (NLM revises it roughly annually), so
// this is a deliberate, occasional refresh (`node scripts/fetch-mesh-terms.mjs`), not
// something the running app does on its own.
//
// Usage: node scripts/fetch-mesh-terms.mjs [year]

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const YEAR = process.argv[2] || "2025";
const MTREES_URL = `https://nlmpubs.nlm.nih.gov/projects/mesh/${YEAR}/meshtrees/mtrees${YEAR}.bin`;
const OUT_FILE = path.join(__dirname, "..", "src", "lib", "mesh-terms.ts");

// MeSH tree branches relevant to a PT/rehab audience. A descriptor is kept if any one of
// its tree numbers falls under one of these prefixes (a MeSH term can appear in more than
// one place in the tree — "poly-hierarchy" — so this is an OR across all of a term's
// tree numbers, not just its first one).
const ALLOWED_TREE_PREFIXES = [
  ["A01", "Body Regions (anatomy)"],
  ["A02", "Musculoskeletal System (anatomy)"],
  ["A08", "Nervous System (anatomy)"],
  ["C05", "Musculoskeletal Diseases"],
  ["C10", "Nervous System Diseases"],
  ["C26", "Wounds and Injuries"],
  ["E02.779", "Physical Therapy Modalities"],
  ["E02.831", "Rehabilitation"],
  ["G11.427", "Musculoskeletal Physiological Phenomena (gait, balance, ROM, strength)"],
  ["H02.010.625", "Physical Therapy Specialty"],
  ["H02.403.355", "Geriatrics"],
  ["H02.403.600", "Neurology"],
  ["H02.403.670", "Pediatrics"],
  ["H02.403.810.494", "Orthopedics"],
  ["H02.403.830", "Sports Medicine"],
  ["I03.450.642.845", "Sports"],
];

function isAllowedTreeNumber(treeNumber) {
  return ALLOWED_TREE_PREFIXES.some(
    ([prefix]) => treeNumber === prefix || treeNumber.startsWith(`${prefix}.`)
  );
}

// MeSH headings use library-catalog inversion for qualifiers — "Fasciitis, Plantar",
// "Ligaments, Articular" — which nobody actually types as an article tag. Un-inverting
// ("plantar fasciitis", "articular ligaments") gives a second, naturally-ordered form to
// match against, in addition to the original.
function invertedForm(heading) {
  const parts = heading.split(", ");
  if (parts.length < 2) return null;
  return parts.reverse().join(" ");
}

async function main() {
  console.log(`Fetching ${MTREES_URL} ...`);
  const res = await fetch(MTREES_URL);
  if (!res.ok) throw new Error(`Fetch failed: ${res.status}`);
  const text = await res.text();
  const lines = text.split("\n").filter(Boolean);

  const terms = new Set();
  for (const line of lines) {
    const semi = line.lastIndexOf(";");
    if (semi === -1) continue;
    const heading = line.slice(0, semi).trim();
    const treeNumber = line.slice(semi + 1).trim();
    if (!heading || !treeNumber) continue;
    if (!isAllowedTreeNumber(treeNumber)) continue;

    terms.add(heading.toLowerCase());
    const inverted = invertedForm(heading);
    if (inverted) terms.add(inverted.toLowerCase());
  }

  const sorted = Array.from(terms).sort();

  const banner = `// Generated by scripts/fetch-mesh-terms.mjs from NLM's MeSH descriptor tree file
// (https://nlmpubs.nlm.nih.gov/projects/mesh/${YEAR}/meshtrees/mtrees${YEAR}.bin), filtered
// to branches relevant to PT/rehab:
${ALLOWED_TREE_PREFIXES.map(([prefix, label]) => `//   ${prefix} — ${label}`).join("\n")}
// A real, point-in-time snapshot — not fetched live (see the script for why).
// Re-run the script to refresh.

/** Lowercased MeSH descriptor terms (and naturally-ordered forms of inverted headings
 *  like "Fasciitis, Plantar" -> "plantar fasciitis") from the PT/rehab-relevant branches
 *  of the MeSH tree. Used by clinical-relevance.ts as a fallback lookup for tags that
 *  aren't in its hand-maintained dictionary. */
export const MESH_CLINICAL_TERMS: ReadonlySet<string> = new Set(${JSON.stringify(sorted, null, 2)});
`;

  writeFileSync(OUT_FILE, banner);
  console.log(`Wrote ${sorted.length} terms to ${OUT_FILE}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
